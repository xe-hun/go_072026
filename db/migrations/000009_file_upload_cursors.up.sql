-- Upload cursors provide an ordered feed of file-upload records for each user.
-- Device identity is nullable only for rows created before upload-device tracking
-- was introduced; new upload requests always provide a registered device ID.
ALTER TABLE file_uploads
    ADD COLUMN cursor BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN device_id VARCHAR(30);

ALTER TABLE file_uploads
    ADD CONSTRAINT file_uploads_device_id_fkey
    FOREIGN KEY (device_id) REFERENCES sync_devices(id);

ALTER TABLE file_uploads
    ADD CONSTRAINT file_uploads_cursor_unique UNIQUE (cursor);

CREATE INDEX file_uploads_owner_cursor_idx
    ON file_uploads (owner_id, cursor);
